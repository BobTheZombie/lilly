static void fail(const char *s){perror(s);exit(1);}
static void reject(const char *s){fprintf(stderr,"lillyboot: %s\n",s);exit(1);}
static void text(const char *s){for(;*s;s++)if((unsigned char)*s<32||(unsigned char)*s>126)reject("configuration must be printable ASCII");}
static int source(int root,const char *path){int fd=fs_open(root,path,O_RDONLY);if(fd<0)fail(path);return fd;}
static bool same_file(int a,int b) {
    unsigned char x[4096],y[4096];off_t offset=0;
    for(;;) {
        ssize_t n=pread(a,x,sizeof x,offset),m=pread(b,y,sizeof y,offset);
        if(n<0||m<0||n!=m)return false;
        if(!n)return true;
        if(memcmp(x,y,(size_t)n))return false;
        offset+=n;
    }
}
static void pe_image(int fd) {
    unsigned char header[64],coff[6];
    if(pread(fd,header,sizeof header,0)!=sizeof header || memcmp(header,"MZ",2))reject("expected EFI PE image");
    unsigned long off=(unsigned long)header[60]|((unsigned long)header[61]<<8)|((unsigned long)header[62]<<16)|((unsigned long)header[63]<<24);
    if(pread(fd,coff,sizeof coff,(off_t)off)!=sizeof coff||memcmp(coff,"PE\0\0",4)||coff[4]!=0x64||coff[5]!=0x86)reject("expected x86-64 EFI image");
}
static void generate(int root,int espfd,const char *version,const char *kernel,const char *initrd,const char *cmdline,bool set_default,unsigned timeout) {
        if(!version||!fs_name(version)||strlen(version)>100||!kernel||!initrd||!cmdline)reject("generate requires safe --version, --kernel, --initrd and --cmdline");
        int k=source(root,kernel);pe_image(k);
        int i=source(root,initrd);struct stat st;if(fstat(i,&st)||st.st_size<=0)reject("empty initrd");
        int c=source(root,cmdline);char *options=fs_read(c,2048);close(c);if(!options)fail("cmdline");
        size_t n=strlen(options);while(n&&(options[n-1]=='\n'||options[n-1]=='\r'))options[--n]=0;
        if(!n)reject("empty kernel command line");
        text(options);
        /* Immutable generation paths keep the previously published entry valid
         * throughout an interrupted update, even when the version is reused. */
        unsigned long nonce;if(getrandom(&nonce,sizeof nonce,0)!=sizeof nonce)fail("random generation");
        char directory[256],path[512],entry[4096];
        snprintf(directory,sizeof directory,"EFI/Lilly/%s-%lx",version,nonce);
        snprintf(path,sizeof path,"%s/vmlinuz.efi",directory);if(fs_copy(k,espfd,path,0))fail("kernel copy");
        snprintf(path,sizeof path,"%s/initrd.img",directory);if(fs_copy(i,espfd,path,0))fail("initrd copy");
        close(k);close(i);
        int len=snprintf(entry,sizeof entry,"# Generated by lillyboot\ntitle LPM Linux (%s)\nversion %s\nlinux /%s/vmlinuz.efi\ninitrd /%s/initrd.img\noptions %s\n",version,version,directory,directory,options);
        if(len<0||(size_t)len>=sizeof entry)reject("entry too long");
        free(options);
        snprintf(path,sizeof path,"loader/entries/lilly-%s.conf",version);
        if(fs_write(espfd,path,entry,(size_t)len,0644,1))fail("publish boot entry");
        if(set_default) {
            len=snprintf(entry,sizeof entry,"# lillyboot native loader configuration\ndefault lilly-%s.conf\ntimeout %u\n",version,timeout);
            if(fs_write(espfd,"loader/lilly.conf",entry,(size_t)len,0644,1))fail("publish loader configuration");
        }
        printf("Generated %s\n",path);

}
static int version_compare(const void *a,const void *b){return strverscmp(*(char *const *)a,*(char *const *)b);}
static void update(int root,int espfd,const char *cmdline,bool set_default,unsigned timeout) {
    int fd=fs_dir(root,"usr/lib/modules",0);if(fd<0)fail("kernel modules directory");
    DIR *dir=fdopendir(fd);if(!dir)fail("kernel modules directory");
    char *versions[256];size_t count=0;struct dirent *e;
    while((e=readdir(dir))) {
        if(e->d_name[0]=='.'||!fs_name(e->d_name)||strlen(e->d_name)>100)continue;
        if(count==256)reject("too many kernels");
        versions[count]=strdup(e->d_name);if(!versions[count++])fail("strdup");
    }
    closedir(dir);qsort(versions,count,sizeof *versions,version_compare);
    unsigned generated=0;
    for(size_t n=0;n<count;n++) {
        char kernel[512],initrd[512];snprintf(kernel,sizeof kernel,"usr/lib/modules/%s/vmlinuz",versions[n]);
        int k=fs_open(root,kernel,O_RDONLY);if(k<0){if(errno==ENOENT){free(versions[n]);continue;}fail(kernel);}close(k);
        snprintf(initrd,sizeof initrd,"boot/initrd-%s.img",versions[n]);
        int i=fs_open(root,initrd,O_RDONLY);
        if(i<0&&errno==ENOENT){snprintf(initrd,sizeof initrd,"boot/initramfs-%s.img",versions[n]);i=fs_open(root,initrd,O_RDONLY);}
        if(i<0)fail("matching initramfs missing; generate it before lillyboot update");
        close(i);
        generate(root,espfd,versions[n],kernel,initrd,cmdline,set_default,timeout);
        generated++;free(versions[n]);
    }
    if(!generated)reject("no installed kernels with matching initramfs found");
}
int main(int argc,char **argv) {
    const char *rootpath="/",*esp="/boot/efi",*version=NULL,*kernel=NULL,*initrd=NULL,*cmdline=NULL,*efi=NULL;
    bool fallback=false,set_default=false;unsigned timeout=5;
    static const struct option opts[]={
        {"root",1,NULL,'r'},{"esp",1,NULL,'e'},{"version",1,NULL,'v'},
        {"kernel",1,NULL,'k'},{"initrd",1,NULL,'i'},{"cmdline",1,NULL,'c'},
        {"efi",1,NULL,'f'},{"fallback",0,NULL,'b'},{"set-default",0,NULL,'d'},
        {"timeout",1,NULL,'t'},{"help",0,NULL,'h'},{0,0,0,0}};
    int opt;while((opt=getopt_long(argc,argv,"",opts,NULL))!=-1) {
        switch(opt) {
        case 'r':rootpath=optarg;break;case 'e':esp=optarg;break;case 'v':version=optarg;break;
        case 'k':kernel=optarg;break;case 'i':initrd=optarg;break;case 'c':cmdline=optarg;break;
        case 'f':efi=optarg;break;case 'b':fallback=true;break;case 'd':set_default=true;break;
        case 't':{char *end;unsigned long n=strtoul(optarg,&end,10);if(!*optarg||*end||n>60)reject("timeout must be 0..60");timeout=(unsigned)n;break;}
        default:puts("Usage: lillyboot [--root ROOT] [--esp /boot/efi] install --efi FILE [--fallback]\n       lillyboot [--root ROOT] [--esp PATH] generate --version VER --kernel FILE --initrd FILE --cmdline FILE [--set-default] [--timeout 5]\n       lillyboot [--root ROOT] [--esp PATH] update [--cmdline /etc/kernel/cmdline] [--set-default]\n       lillyboot [--root ROOT] [--esp PATH] status");return opt=='h'?0:1;
        }
    }
    if(optind+1!=argc)reject("one command required");
    const char *command=argv[optind];
    int root=fs_root(rootpath);if(root<0)fail(rootpath);
    int espfd=fs_dir(root,esp,0);if(espfd<0)fail("ESP (mount it first)");
    if(!strcmp(rootpath,"/")) {
        struct statfs fs;
        if(fstatfs(espfd,&fs)||fs.f_type!=MSDOS_SUPER_MAGIC)reject("live ESP must be a mounted FAT filesystem; mount /boot/efi first");
    }
    if(!strcmp(command,"install")) {
        if(!efi)reject("install requires --efi");
        int fd=source(root,efi);pe_image(fd);
        bool replace_fallback=false;
        if(fallback) {
            int old=fs_open(espfd,"EFI/BOOT/BOOTX64.EFI",O_RDONLY);
            if(old>=0) {
                int own=fs_open(espfd,"EFI/Lilly/lillybootx64.efi",O_RDONLY);
                if(own<0 || !same_file(old,own))reject("fallback belongs to another loader; preserved");
                close(own);close(old);replace_fallback=true;
            } else if(errno!=ENOENT)fail("fallback path");
        }
        if(fs_copy(fd,espfd,"EFI/Lilly/lillybootx64.efi",1))fail("install EFI loader");
        if(fallback) {
            if(lseek(fd,0,SEEK_SET)<0)fail("seek");
            if(fs_copy(fd,espfd,"EFI/BOOT/BOOTX64.EFI",replace_fallback))fail("fallback exists or cannot be installed (preserved)");
        }
        close(fd);puts("Installed EFI/Lilly/lillybootx64.efi; firmware variables unchanged");
    } else if(!strcmp(command,"generate")) {
        generate(root,espfd,version,kernel,initrd,cmdline,set_default,timeout);
    } else if(!strcmp(command,"update")) {
        update(root,espfd,cmdline?cmdline:"/etc/kernel/cmdline",set_default,timeout);
    } else if(!strcmp(command,"status")) {
        int fd=fs_open(espfd,"EFI/Lilly/lillybootx64.efi",O_RDONLY);printf("loader: %s\n",fd>=0?"installed":"absent");if(fd>=0)close(fd);
        int d=fs_dir(espfd,"loader/entries",0);
        if(d>=0){DIR *dir=fdopendir(d);if(!dir)fail("entries");struct dirent *e;while((e=readdir(dir)))if(!strncmp(e->d_name,"lilly-",6)&&fs_name(e->d_name))puts(e->d_name);closedir(dir);}
        else if(errno!=ENOENT)fail("entries");
    } else reject("unknown command");
    close(espfd);close(root);return 0;
}
